func TestParseTranscriptKeepsPromptsAndProseOnly(t *testing.T) {
	jsonl := strings.Join([]string{
		`{"type":"session_start","id":"s","cwd":"/w"}`,
		`{"type":"message","id":"context-1","message":{"role":"user","content":[{"type":"text","text":"<system-reminder>skills</system-reminder>"}]}}`,
		`{"type":"message","message":{"role":"user","content":[{"type":"text","text":"Fix the login bug"},{"type":"text","text":"<system-reminder>date</system-reminder>"}]}}`,
		`{"type":"message","message":{"role":"assistant","content":[{"type":"thinking","thinking":"hmm"},{"type":"text","text":"Looking at auth.ts"},{"type":"tool_use","id":"t","name":"Read","input":{}}]}}`,
		`{"type":"message","message":{"role":"user","content":[{"type":"tool_result","content":"file"}]}}`,
		`{"type":"todo_state","todos":[]}`,
		"not json",
		`{"type":"message","message":{"role":"user","content":"不对，是 session.ts"}}`,
	}, "\n")
	turns := ParseTranscript(jsonl)
	eq(t, turns, []Turn{{"user", "Fix the login bug"}, {"assistant", "Looking at auth.ts"}, {"user", "不对，是 session.ts"}})
	eq(t, UserPromptCount(turns), 2)
}

func writeSessionFile(t *testing.T, dir, folder, id string, lines ...string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Join(dir, folder), 0o777); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, folder, id+".jsonl"), []byte(strings.Join(lines, "\n")), 0o666); err != nil {
		t.Fatal(err)
	}
}

func writeFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(body), 0o666); err != nil {
		t.Fatal(err)
	}
}

func TestFindSessionWorkspaceReadsTheSessionStartLine(t *testing.T) {
	dir := t.TempDir()
	writeSessionFile(t, dir, "-Users-dev-other", "aaa", `{"type":"session_start","cwd":"/Users/dev/other"}`)
	writeSessionFile(t, dir, "-Users-dev-app", "bbb", `{"type":"session_start","id":"bbb","cwd":"/Users/dev/app"}`, `{"type":"message","message":{"role":"user","content":[]}}`)
	eq(t, FindSessionWorkspace(dir, "bbb"), "/Users/dev/app")
}

func TestFindSessionWorkspaceAnswersNothingForWhatItCannotPlace(t *testing.T) {
	dir := t.TempDir()
	writeSessionFile(t, dir, "-x", "ccc", `{"type":"message"}`)
	eq(t, FindSessionWorkspace(dir, "missing"), "")
	eq(t, FindSessionWorkspace(dir, "../etc/passwd"), "")
	eq(t, FindSessionWorkspace(dir, "ccc"), "")
	eq(t, FindSessionWorkspace(filepath.Join(dir, "nope"), "ccc"), "")
}


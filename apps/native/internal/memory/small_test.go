func TestMarkdownWritesOneReadOnlyFilePerMemoryCorrectionsFirst(t *testing.T) {
	s, dir := openTestStore(t)
	app := Slot{Scope: ScopeProject, Workspace: "/Users/dev/my app"}
	convention := add(t, s, app, "Tests sit next to the code", CategoryConvention)
	add(t, s, app, "Use pnpm, not npm", CategoryCorrection)
	path := must[string](t)(ExportMarkdown(s, app))
	eq(t, path, filepath.Join(dir, MarkdownPath(app)))
	if !regexp.MustCompile(`^projects/my-app-[0-9a-f]{8}\.md$`).MatchString(MarkdownPath(app)) {
		t.Fatalf("path %q", MarkdownPath(app))
	}
	b := must[[]byte](t)(os.ReadFile(path))
	text := string(b)
	if !regexp.MustCompile(`^<!-- Generated by Droi .*not read back`).MatchString(text) {
		t.Fatal(text)
	}
	if !strings.Contains(text, "# Memory: /Users/dev/my app") || strings.Index(text, "## Corrections") > strings.Index(text, "## Conventions") {
		t.Fatal(text)
	}
	if !strings.Contains(text, "- Tests sit next to the code (`"+convention.ID+"`, "+convention.Day+")") {
		t.Fatal(text)
	}
	info := must[os.FileInfo](t)(os.Stat(path))
	eq(t, info.Mode().Perm(), os.FileMode(0o444))
}

func TestMarkdownRewritesTheFileAfterAChangeReadOnlyOrNot(t *testing.T) {
	s, dir := openTestStore(t)
	added := add(t, s, GlobalSlot, "Answer tersely", CategoryPreference)
	must[string](t)(ExportMarkdown(s, GlobalSlot))
	must[bool](t)(s.Remove(added.ID))
	path := must[string](t)(ExportMarkdown(s, GlobalSlot))
	eq(t, path, filepath.Join(dir, "global.md"))
	if !strings.Contains(string(must[[]byte](t)(os.ReadFile(path))), "No entries yet.") {
		t.Fatal("not rewritten")
	}
}


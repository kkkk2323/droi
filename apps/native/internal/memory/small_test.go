func TestIsMemorySessionTranscriptReadsTheTag(t *testing.T) {
	dir := t.TempDir()
	writeSessionFile(t, dir, "-w", "mem", `{"type":"session_start","cwd":"/w"}`)
	transcript := FindSessionTranscript(dir, "mem")
	eq(t, SessionSettingsFile(transcript), filepath.Join(dir, "-w", "mem.settings.json"))
	eq(t, IsMemorySessionTranscript(transcript), false)
	writeFile(t, SessionSettingsFile(transcript), `{"tags":[{"name":"droi.draft"}]}`)
	eq(t, IsMemorySessionTranscript(transcript), false)
	writeFile(t, SessionSettingsFile(transcript), `{"tags":[{"name":"droi.memory"}]}`)
	eq(t, IsMemorySessionTranscript(transcript), true)
}

func TestIsScratchSessionTranscriptReadsTheInheritedTag(t *testing.T) {
	dir := t.TempDir()
	writeSessionFile(t, dir, "-Users-me--droi-chats-2026-09-30-25e965", "chat", `{"type":"session_start","cwd":"/Users/me/.droi/chats/2026-09-30-25e965"}`)
	transcript := FindSessionTranscript(dir, "chat")
	eq(t, IsScratchSessionTranscript(transcript), false)
	writeFile(t, SessionSettingsFile(transcript), `{"tags":[{"name":"droi.scratch"},{"name":"droi.continues","metadata":{"parent":"p"}}]}`)
	eq(t, IsScratchSessionTranscript(transcript), true)
	eq(t, IsMemorySessionTranscript(transcript), false)
}
